"""Reader-facing export formats for episodes.

Converts a saved episode (metadata + story markdown) into clean plain text,
a standalone styled HTML document, and an EPUB ebook. The story markdown is
the canonical source; these formatters only re-shape it for reading/sharing.

Story structure conventions handled here (matching StoryGenerator.parse_days):
    "## DAY 1: Title"        -> day section
    "### Chapter 1: Title"   -> chapter within the day
"""

import html
import re
from dataclasses import dataclass, field
from typing import Any

